#ifndef _ITEM_BANK_H_
#define _ITEM_BANK_H_

#include <stdint.h>

/*  ============================================================================
    번호로 주소를 매기는 값 저장소

    device bank (sensor.h) 는 "장치 여러 대가 같은 값 몇 가지를 보고한다" 는
    모양이다 -- 온습도 센서 64대가 각각 온도와 습도를 낸다. 행이 장치고 열이
    항목이다.

    Linknet3500 이 붙이는 장비는 그 모양이 아니다. 장비는 두 대뿐이고, 한 대가
    100개 넘는 서로 다른 항목을 낸다. 그 항목들은 서로 단위도 의미도 달라서
    공통 열로 묶이지 않는다.

    그래서 여기는 평면이다. 장비 하나에 번호 하나당 값 하나.

        22210.2.<장비>.<번호>.0

    번호가 곧 OID 이고, 뱅크의 주소이고, 웹 화면에 찍히는 숫자다. 셋을 따로
    두면 어긋나므로 하나로 쓴다.

    device bank 는 그대로 남는다. 접점 입력과 S/T/R 은 계속 그쪽을 쓴다.
    ============================================================================ */

/*  장비 슬롯. OID 의 <장비> 자리에 들어갈 값은 item_oid_device() 가 준다 --
    항온항습기는 1, UPS 는 12082 로 자릿수가 달라서 슬롯 번호와 다르다. */
#define ITEM_DEV_HVAC       0       /* 항온항습기  22210.2.1.<번호>.0     */
#define ITEM_DEV_UPS        1       /* UPS         22210.2.12082.<번호>.0 */
#define ITEM_DEV_CNT        2

/*  쓰는 번호는 1-139 다. 0번은 없다.

        1-100       데이터 항목
        111-126     접점 입력 16개
        130-139     SET 제어

    139 는 OID 서브식별자가 1바이트로 안 들어가서(127 초과) BER 로 2바이트가
    된다. MAX_OID 가 그만큼 여유가 있어야 한다 -- snmp.h 참고. */
#define ITEM_NUM_MAX        140     /* 0 .. 139, 0번은 비워둔다 */

/*  한 항목이 무엇인지. 프로토콜이 자기 항목을 표로 한 번 선언하면 SNMP 등록과
    웹 표시가 거기서 나온다. g_value_columns[] 나 g_serial_protocol[] 과 같은
    방식이다 -- 사실을 한 곳에만 적는다. */
typedef struct {
    uint8_t     num;        /* OID 번호 = 뱅크 주소                       */
    const char *name;       /* 웹에 찍히는 이름                            */
    int8_t      scale;      /* 10의 거듭제곱. -1 이면 raw 2741 -> 274.1   */
    const char *unit;       /* "V", "A", "" ...                           */

    /*  이 값이 되는 순간 트랩을 한 번 보낸다. 0 이면 안 보낸다.

        고객 문서가 "경보상태 값이 1이면 트랩 한번 발생" 이라고 정했다. 한 번
        이라는 말이 중요해서, 값이 서 있는 동안이 아니라 서는 순간에만 나간다.
        경보는 1, 통신 경보와 접점은 2 -- 항목마다 다르므로 숫자로 적는다.

        임계값 비교가 아닌 이유는, 이 항목들이 온도처럼 범위를 넘나드는 값이
        아니라 정해진 숫자 하나로 상태를 말하기 때문이다. device bank 쪽 열별
        임계값(snmpHandler.c)은 그쪽 값들을 위해 그대로 남는다. */
    uint8_t     trap_on;

    /*  1 이면 웹 화면에만 나가고 SNMP OID 는 만들지 않는다.

        UPS 가 그렇다. 고객 화면(슬라이드 10, 11)은 232 프로토콜의 내부 번호
        30-99 를 그대로 보여주는데, SNMP 로 내보내는 것은 따로 매긴 1-28 뿐
        이다. 번호 공간은 같으니 여기 함께 두고, OID 를 만들 때만 걸러낸다.

        값을 웹에는 주면서 SNMP 에는 안 주는 것이 이상해 보이지만, 그 둘은
        원래 다른 약속이다 -- 웹은 우리 화면이고 OID 는 고객의 관리 프로그램이
        등록해 쓰는 목록이다. */
    uint8_t     web_only;
} ItemDef;

/*  전부 지우고 등록을 비운다. 부팅 때 한 번. */
void item_bank_init(void);

/*  `dev` 가 내보낼 항목표를 등록한다. 표는 정적이어야 한다 -- 포인터만 들고
    있지 복사하지 않는다.

    한 장비에 표를 여러 개 걸 수 있다. 항온항습기가 그렇다: 프로토콜이 자기
    데이터 1-76 을 걸고, 접점 입력이 111-126 을 따로 건다. 둘은 서로를 모르고
    시작 시점도 다른데 OID 는 같은 가지를 쓴다.

    같은 `defs` 포인터로 다시 부르면 그 자리를 덮는다 -- 태스크가 재시작해도
    표가 두 벌로 늘지 않는다.

    돌려주는 값: 0 성공, -1 인자가 틀림, -2 표가 못 쓸 번호를 들고 있음,
    -3 이미 등록된 번호와 겹침, -4 이 장비의 표 자리가 없음. */
int item_bank_register(uint8_t dev, const ItemDef *defs, uint16_t count);

/*  값 읽고 쓰기. 등록되지 않은 번호에 쓰면 -2 를 돌려주고 버린다 -- 표에 없는
    번호가 조용히 저장돼서 OID 없이 떠 있는 것보다 낫다. */
int item_set(uint8_t dev, uint8_t num, int32_t value);
int item_get(uint8_t dev, uint8_t num, int32_t *out);

/*  그 번호가 등록돼 있나. 0 = 아님. */
uint8_t item_is_registered(uint8_t dev, uint8_t num);

/*  그 번호가 SNMP OID 를 가지나. 등록됐고 web_only 가 아니면 1.
    SNMP 표를 만드는 쪽이 이것으로 거른다. */
uint8_t item_has_oid(uint8_t dev, uint8_t num);

/*  OID 의 <장비> 자리 값. 슬롯 번호가 아니라 실제 서브식별자다. */
uint32_t item_oid_device(uint8_t dev);

/*  등록된 항목을 차례로 훑을 때 쓴다. SNMP 테이블을 만들 때 필요하다. */
uint16_t item_count(uint8_t dev);
const ItemDef *item_at(uint8_t dev, uint16_t idx);

/*  등록이 바뀔 때마다 하나씩 오른다.

    SNMP 표는 등록된 항목으로 만드는데, 표를 만드는 쪽(SNMP 태스크)과 등록하는
    쪽(프로토콜 태스크)이 서로 언제 도는지 모른다. 이 숫자가 달라졌으면 다시
    만들면 되고, 순서를 맞추려고 둘을 붙들어 맬 필요가 없다. */
uint32_t item_bank_generation(void);

#endif /* _ITEM_BANK_H_ */
