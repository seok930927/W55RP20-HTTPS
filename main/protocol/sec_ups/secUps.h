#include "uartHandler.h"    /* SerialPort */

/*  ============================================================================
    SEC UPS (YES-SEC-V2T) — RS-232, 19200-8-N-1

    우리가 먼저 묻고 상대가 답하는 동기 폴러다. 질의는 다섯 가지고, 한 바퀴를
    돌면 UPS 상태 전부가 갱신된다.

        송신   ^P003ST1
        수신   ^D019,,3,,,,2741,-034,27
               ││└┬┘└──────────┬──────┘
               ││ │            └ 데이터 (길이만큼)
               ││ └────────────── 데이터 길이, 10진 3자리
               │└──────────────── 응답 표시
               └───────────────── 시작 문자

    길이가 헤더에 들어 있어서 프레이밍이 쉽다. 5바이트를 읽어 길이를 알아낸 뒤
    그만큼 더 읽으면 한 프레임이다 -- 구분자를 찾아 헤맬 일도, 침묵을 재야 할
    일도 없다.

    데이터는 쉼표로 나눈다. 값의 자릿수가 고정이 아니어서 -- 같은 항목이 1 로
    올 때도 있고 1111 로 올 때도 있다 -- 시작 자리를 표에 박아두면 짧은 값이
    하나만 와도 그 뒤가 전부 밀린다. 비어 있는 항목은 빈 칸으로 오지만
    (ST1 응답 앞부분 ",,3,,,," 가 그렇다) 쉼표는 그대로 찍혀 오므로 세다가
    어긋나지 않는다.

    ----------------------------------------------------------------------------
    번호 두 벌

    이 프로토콜의 항목 번호(30-99)는 우리 내부용이다. 문서의 표가 그 번호로
    적혀 있어서 파싱할 때 쓰지만, 밖으로는 나가지 않는다.

    SNMP 로 나가는 것은 따로 매긴 번호(1-10, 21-25)이고, 대부분 내부 값을
    가공한 것이다 -- 입력전압 R-S 는 내부 87번을 10으로 나눈 값이다. 그 대응은
    고객 문서 슬라이드 8 에 있고, 이 파일의 ups_publish() 가 그대로 옮겼다.
    ============================================================================ */

/*  항목표를 itemBank 에 걸어둔다. 부팅 때 한 번, 태스크가 뜨는지와 무관하게.

    번호와 이름은 컴파일 타임에 정해진 것이라 UPS 가 붙어 있는지, 포트에
    이 프로토콜을 골랐는지와 아무 상관이 없다. 걸어두지 않으면 그 번호가
    어디에도 없어서 OID 도 안 생기는데, 고객이 관리 프로그램에 OID 를 등록하는
    일은 장비를 연결하기 전에 한다. */
void secUps_register(void);

void secUps_task(void *argument);

