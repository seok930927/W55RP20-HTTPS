/*  ============================================================================
    항온항습기 — Modbus RTU, RS-485, 9600-8-N-1

    한 번 물어서 전부 받아온다. 87개 레지스터가 한 덩어리로 붙어 있어서
    질의도 하나다.

        송신   01 03 0000 0057 0434            (8 바이트)
        수신   01 03 AE <레지스터 87개> CRC    (179 바이트)

    앞의 modbusMaster.c 가 프레임과 CRC 를 맡고, 이 파일은 "몇 번 레지스터가
    무슨 항목인가" 만 안다.

    ----------------------------------------------------------------------------
    레지스터 번호와 OID 번호는 다르다

    고객 문서는 응답을 바이트 위치로 설명한다 -- "3,4 BYTE 는 현재온도" 같은
    식이다. 0번부터 세면 addr/func/len 이 0,1,2 이므로 레지스터 n 은 바이트
    3+2n, 4+2n 이다. 현재온도는 레지스터 0번이고, 캡처된 00DE = 222 = 22.2도가
    이 계산을 확인해 준다.

    그런데 SNMP 로 나가는 번호는 그 순서가 아니다. 설정온도가 1번인데 레지스터
    로는 81번이고, 현재온도는 3번인데 레지스터 0번이다. 그래서 아래 표가
    둘을 나란히 들고 있다.

    표를 다 채우고 나면 OID 번호 1번부터 76번까지가 빠짐없이 한 번씩 쓰인다.
    문서의 표를 잘못 읽었다면 번호가 겹치거나 비었을 텐데 그렇지 않으니,
    대응이 맞다고 볼 근거가 된다.

    통신 상태만 레지스터가 없다. 우리가 판단해서 100번으로 올린다.
    ============================================================================ */

